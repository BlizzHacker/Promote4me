/**
 * Promote4.me Build Version Injector
 * 
 * Injects the current version from package.json into a generated 
 * src/version.js file that gets imported by the app.
 * 
 * This replaces the old 50+ apply-*.mjs patch chain that mutated 
 * source files in-place.
 */
import fs from 'fs';

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const version = pkg.version || '4.0.0';

const content = `// Auto-generated by scripts/build-version.mjs — DO NOT EDIT
export const VERSION = '${version}';
export const BUILD_TIME = '${new Date().toISOString()}';
`;

fs.writeFileSync('src/version.js', content);
console.log(`Build version ${version} written to src/version.js`);
